import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

for (const width of [320, 390, 1440]) {
  test(`Irvine results emphasize provider actions rather than explanations at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/')
    await page.getByRole('button', { name: 'City', exact: true }).click()
    await page.getByLabel('California city').fill('Irvine')
    await page.getByRole('button', { name: 'Find support options' }).click()
    const results = page.locator('section[aria-label="Orange County Behavioral Health Plan sites"]')
    await expect(results.getByRole('heading', { name: 'Progeny Psychiatric Group - Irvine', exact: true })).toBeVisible()
    await expect(results.getByRole('link', { name: /^Open in maps:/ })).toBeVisible()
    await expect(results.getByRole('link', { name: '949-722-7118', exact: true })).toBeVisible()
    await expect(results.getByText('Psychiatry & Neurology Psychiatry', { exact: true })).toBeHidden()
    await expect(results.getByText(/Orange County Medi-Cal BHP provider-site subset/)).toBeHidden()
    await expect(page.getByText(/County selection provides a referral phone/)).toHaveCount(0)
    await expect(page.getByText(/Call before visiting to confirm services/)).toBeHidden()
    await expect(page.getByText('Call to confirm cost, eligibility, and availability.', { exact: true })).toBeVisible()
    const county = page.locator('section[aria-label="County mental health plan"]')
    await expect(county).toBeHidden()
    await expect(page.getByRole('link', { name: 'DHCS county mental health plans', exact: true })).toBeHidden()
    await page.locator('section[aria-labelledby="local-support-heading"]').screenshot({ path: `test-results/concise-irvine-default-${width}.png` })
    await results.locator('article summary').click()
    await expect(results.getByText('Psychiatry & Neurology Psychiatry', { exact: true })).toBeVisible()
    await results.getByText('Source & details', { exact: true }).click()
    await expect(results.getByText(/Orange County Medi-Cal BHP provider-site subset/)).toBeVisible()
    const referral = page.getByText('County referral · Orange', { exact: true })
    await referral.focus()
    await page.keyboard.press('Enter')
    await expect(county).toBeVisible()
    await expect(county.getByRole('link', { name: 'Call county plan', exact: true })).toBeVisible()
    const accessibility = await new AxeBuilder({ page }).include('section[aria-labelledby="local-support-heading"]').withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(accessibility.violations).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    await page.screenshot({ path: `test-results/concise-irvine-${width}.png`, fullPage: true })
  })
}

test('county referral remains immediately available when there are no exact provider records', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('California county').selectOption('Colusa')
  await page.getByRole('button', { name: 'Find support options' }).click()
  const county = page.locator('section[aria-label="County mental health plan"]')
  await expect(county).toBeVisible()
  await expect(county.getByRole('link', { name: 'Call county plan', exact: true })).toBeVisible()
})
